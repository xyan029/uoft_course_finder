#!/usr/bin/env python3
"""Regenerate the trimmed HTML fixtures under tests/fixtures/ from live pages.

Usage::

    python3 scripts/refresh_fixtures.py            # fetch live and trim
    python3 scripts/refresh_fixtures.py --from DIR # trim already-saved pages

Each fixture keeps the real markup of a few course rows (plus the pager, when
present) inside a minimal HTML skeleton, with scripts, styles, navigation and
tracking removed. Run this after a calendar site changes, check the diff, and
update the parser and tests to match.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from uoft_course_finder.calendars import CALENDARS
from uoft_course_finder.httpclient import fetch

FIXTURES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "fixtures")

# (campus, keyword, course codes to keep). AMS320H1 is kept on purpose: its
# aria-label is truncated by the site, which exercises the parser fallback.
SELECTION = {
    "artsci": ("geography", ["AMS320H1", "GGR107H1", "GGR246H1"]),
    "utm": ("algorithm", ["CSC104H5", "CSC263H5", "CSC373H5"]),
    "utsc": ("algorithm", ["CSCB36H3", "CSCC11H3", "CSCC37H3"]),
}

SKELETON = """<!DOCTYPE html>
<html lang="en" dir="ltr">
<head>
<meta charset="utf-8" />
<title>{title}</title>
</head>
<body>
<!-- Trimmed fixture generated by scripts/refresh_fixtures.py from {url} -->
<div class="region region-content">
{form}
<div class="view view-search-courses">
  <div class="view-content">
{rows}
  </div>
{pager}
</div>
</div>
</body>
</html>
"""

ROW_START_RE = re.compile(r'<div class="views-row">\s*<h3 class="js-views-accordion-group-header">')
DIV_TOKEN_RE = re.compile(r"<div\b|</div>", re.IGNORECASE)
PAGER_RE = re.compile(r"<nav[^>]*\bpager\b.*?</nav>", re.DOTALL)
FORM_RE = re.compile(r'<form class="views-exposed-form[^>]*>.*?</form>', re.DOTALL)
KEYWORD_INPUT_RE = re.compile(r"<input[^>]*name=\"course_keyword\"[^>]*/?>")


def extract_rows(page: str) -> list:
    """Return the outer ``views-row`` block (heading + body) of every course."""
    rows = []
    for start in ROW_START_RE.finditer(page):
        depth = 0
        for token in DIV_TOKEN_RE.finditer(page, start.start()):
            depth += 1 if token.group(0).lower() == "<div" else -1
            if depth == 0:
                rows.append(page[start.start() : token.end()])
                break
    return rows


def trim(page: str, codes: list, url: str, title: str) -> str:
    def heading(row: str) -> str:
        return row.split("</h3>", 1)[0]

    rows = [row for row in extract_rows(page) if any(code in heading(row) for code in codes)]
    missing = [code for code in codes if not any(code in heading(row) for row in rows)]
    if missing:
        raise SystemExit(f"{title}: could not find rows for {', '.join(missing)}")
    pager = PAGER_RE.search(page)
    form_html = ""
    if FORM_RE.search(page):
        # Keep only the keyword input; drop the long select lists.
        keyword_input = KEYWORD_INPUT_RE.search(page)
        form_html = (
            '<form class="views-exposed-form" method="get">\n'
            f"  {keyword_input.group(0) if keyword_input else ''}\n"
            "</form>"
        )
    return SKELETON.format(
        title=title,
        url=url,
        form=form_html,
        rows="\n".join(rows),
        pager=pager.group(0) if pager else "",
    )


def main(argv: list) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--from", dest="source_dir", help="directory of saved <campus>.html pages")
    args = parser.parse_args(argv)

    os.makedirs(FIXTURES, exist_ok=True)
    for campus, (keyword, codes) in SELECTION.items():
        calendar = CALENDARS[campus]
        url = calendar.build_search_url(keyword)
        if args.source_dir:
            with open(os.path.join(args.source_dir, f"{campus}.html"), encoding="utf-8") as fh:
                page = fh.read()
        else:
            page = fetch(url)
        fixture = trim(page, codes, url, f"{calendar.name} search results")
        target = os.path.join(FIXTURES, f"{campus}_search.html")
        with open(target, "w", encoding="utf-8") as fh:
            fh.write(fixture)
        print(f"wrote {os.path.relpath(target)} ({len(fixture)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
